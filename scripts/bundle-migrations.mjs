#!/usr/bin/env node
/**
 * Concatenates supabase/migrations/*.sql into a single supabase/setup.sql so the
 * whole schema can be pasted into the Supabase SQL editor in one go.
 *
 *   npm run db:bundle
 *
 * Every migration is written to be idempotent (create ... if not exists,
 * drop policy if exists before create policy, create or replace function), so
 * running the bundle on a project that already has some of it applied is safe.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const migrationsDir = fileURLToPath(new URL("../supabase/migrations/", import.meta.url));
const outputFile = fileURLToPath(new URL("../supabase/setup.sql", import.meta.url));

const files = readdirSync(migrationsDir)
  .filter((name) => name.endsWith(".sql"))
  .sort();

if (files.length === 0) {
  console.error("No migrations found.");
  process.exit(1);
}

const header = [
  "-- =============================================================================",
  "-- Review Ops - complete database setup (generated by `npm run db:bundle`).",
  "--",
  "-- Paste this whole file into the Supabase SQL editor and run it once.",
  "-- It is idempotent: re-running it on a partially set-up project is safe.",
  "--",
  `-- Built from: ${files.join(", ")}`,
  "-- =============================================================================",
  "",
].join("\n");

const body = files
  .map((name) => {
    const sql = readFileSync(`${migrationsDir}${name}`, "utf8").trimEnd();
    return [
      "",
      "-- ----------------------------------------------------------------------------",
      `-- >>> ${name}`,
      "-- ----------------------------------------------------------------------------",
      sql,
      "",
    ].join("\n");
  })
  .join("\n");

writeFileSync(outputFile, `${header}${body}`, "utf8");
console.log(`Wrote supabase/setup.sql from ${files.length} migrations (${files.join(", ")}).`);
